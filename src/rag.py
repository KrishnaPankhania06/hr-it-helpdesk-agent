"""RAG over the company policy documents.

Policy markdown files are chunked per section, embedded with Ollama
(nomic-embed-text) and stored in ChromaDB. Answers are generated by the
local chat model and must be grounded in the retrieved chunks with sources.
"""
import glob
import os

import chromadb

import ollama_client

POLICY_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data", "policy_docs")
COLLECTION_NAME = "policy_docs"


class OllamaEmbeddingFunction:
    """ChromaDB embedding function backed by Ollama."""

    def __call__(self, input):
        return [ollama_client.embed(t) for t in input]

    def embed_query(self, input):
        return self.__call__(input)

    def embed_documents(self, input):
        return self.__call__(input)

    def name(self):
        return "ollama-nomic-embed-text"


def chunk_markdown(text, source):
    """Split a markdown policy doc into section chunks."""
    chunks = []
    current_heading = "Intro"
    current_lines = []
    for line in text.splitlines():
        if line.startswith("#"):
            if current_lines:
                chunks.append((current_heading, "\n".join(current_lines).strip()))
            current_heading = line.lstrip("#").strip()
            current_lines = [line]
        else:
            current_lines.append(line)
    if current_lines:
        chunks.append((current_heading, "\n".join(current_lines).strip()))
    return [
        {"id": f"{source}:::{i}", "text": body, "source": source, "heading": heading}
        for i, (heading, body) in enumerate(chunks)
        if body
    ]


def build_collection():
    client = chromadb.Client()
    collection = client.get_or_create_collection(
        name=COLLECTION_NAME,
        embedding_function=OllamaEmbeddingFunction(),
        metadata={"hnsw:space": "cosine"},
    )
    if collection.count() == 0:
        docs, ids, metas = [], [], []
        for path in sorted(glob.glob(os.path.join(POLICY_DIR, "*.md"))):
            source = os.path.basename(path)
            with open(path, encoding="utf-8") as f:
                for chunk in chunk_markdown(f.read(), source):
                    ids.append(chunk["id"])
                    docs.append(chunk["text"])
                    metas.append({"source": chunk["source"], "heading": chunk["heading"]})
        collection.add(ids=ids, documents=docs, metadatas=metas)
    return collection


def retrieve(collection, question, k=4):
    result = collection.query(query_texts=[question], n_results=k)
    chunks = []
    for doc, meta, dist in zip(
        result["documents"][0], result["metadatas"][0], result["distances"][0]
    ):
        chunks.append({"text": doc, "source": meta["source"], "heading": meta["heading"], "distance": dist})
    return chunks


RAG_SYSTEM = (
    "You are an HR/IT helpdesk assistant for a company. Answer the employee's "
    "question using ONLY the policy excerpts below. Be concise (2-5 sentences). "
    "Answer the actual question asked; for eligibility questions, state plainly "
    "whether the person is eligible or not, and any waiting period or exception. "
    "First quote the exact policy sentence that answers the question, then give "
    "your answer based only on that quote. "
    "Cite the document each fact comes from, like [source: leave_policy.md]. "
    "If the excerpts do not cover the question, say honestly that the policy "
    "documents do not cover it and suggest contacting the HR or IT team. "
    "Never invent policy details. If none of the excerpts even mention the topic "
    "asked about, the answer is that the documents do not cover it - never use "
    "an excerpt about a different topic to answer."
)


FEWSHOT_USER = (
    "POLICY EXCERPTS:\n"
    "[leave_policy.md - Carry Over]\n"
    "Up to 6 unused annual leave days carry over into the next calendar year. "
    "Anything beyond 6 days lapses on 31 December.\n\n"
    "QUESTION: Can I carry over 10 unused leave days into next year?"
)
FEWSHOT_ASSISTANT = (
    'The policy says: "Up to 6 unused annual leave days carry over into the next '
    'calendar year. Anything beyond 6 days lapses on 31 December." So no - only '
    "up to 6 days carry over, not 10. [source: leave_policy.md]"
)

FEWSHOT2_USER = (
    "POLICY EXCERPTS:\n"
    "[it_security_policy.md - Devices]\n"
    "Personal laptops may not be used for company work. Only company-issued "
    "devices are allowed.\n\n"
    "QUESTION: Can I use my personal laptop for company work?"
)
FEWSHOT2_ASSISTANT = (
    'The policy says: "Personal laptops may not be used for company work." '
    "So no - you can only use a company-issued device for company work. "
    "[source: it_security_policy.md]"
)


NOT_COVERED = (
    "The policy documents do not cover this. I checked the available HR and IT "
    "policies and could not find anything on it, so I don't want to guess. "
    "Please contact the HR or IT team for a definitive answer."
)

# Cosine distance above this means no retrieved chunk is really about the
# question - answering from it would be guessing. (Covered questions score
# ~0.14-0.23 on this policy set; uncovered ones land above 0.3.)
RELEVANCE_CUTOFF = 0.30


def answer_policy_question(collection, question):
    """Retrieve + generate. Returns (answer_text, sources)."""
    chunks = retrieve(collection, question)
    if not chunks or chunks[0]["distance"] > RELEVANCE_CUTOFF or not _covers_topic(chunks, question):
        return NOT_COVERED, []
    context = "\n\n---\n\n".join(
        f"[{c['source']} - {c['heading']}]\n{c['text']}" for c in chunks
    )
    answer = ollama_client.chat(
        [
            {"role": "system", "content": RAG_SYSTEM},
            {"role": "user", "content": FEWSHOT_USER},
            {"role": "assistant", "content": FEWSHOT_ASSISTANT},
            {"role": "user", "content": FEWSHOT2_USER},
            {"role": "assistant", "content": FEWSHOT2_ASSISTANT},
            {"role": "user", "content": f"POLICY EXCERPTS:\n{context}\n\nQUESTION: {question}"},
        ],
        temperature=0,
    )
    answer = _verify_answer(context, question, answer)
    sources = sorted({c["source"] for c in chunks[:2]})
    return answer, sources


def _covers_topic(chunks, question):
    """Second relevance signal: do the retrieved excerpts actually discuss the
    asked topic? Small embedding models can rank a same-domain-but-off-topic
    chunk as close, so the chat model double-checks before we generate."""
    excerpts = "\n\n".join(c["text"] for c in chunks[:3])
    reply = ollama_client.chat(
        [
            {
                "role": "system",
                "content": (
                    "You check whether policy excerpts discuss the topic of a question. "
                    "Reply with exactly one word: YES if any excerpt talks about the "
                    "asked topic, NO if none do. Related-but-different topics are NO."
                ),
            },
            {"role": "user", "content": f"EXCERPTS:\n{excerpts}\n\nQUESTION: {question}"},
        ],
        temperature=0,
    )
    return reply.strip().upper().startswith("YES")


def _verify_answer(context, question, draft):
    """Second-pass check: does the draft match the retrieved policy text?

    Small local models sometimes quote the right sentence and still draw the
    wrong conclusion, so a verifier pass re-reads the excerpts and corrects
    the draft when it contradicts them.
    """
    verdict = ollama_client.chat(
        [
            {
                "role": "system",
                "content": (
                    "You check a draft answer against policy excerpts. If the draft's "
                    "conclusion follows from the excerpts, reply with exactly OK. If it "
                    "contradicts them, reply with the corrected answer in 2-4 sentences, "
                    "citing [source: <file>] like the draft does."
                ),
            },
            {
                "role": "user",
                "content": (
                    f"POLICY EXCERPTS:\n{context}\n\nQUESTION: {question}\n\n"
                    f"DRAFT ANSWER:\n{draft}"
                ),
            },
        ],
        temperature=0,
    )
    if verdict.strip().upper().startswith("OK"):
        return draft
    return verdict.strip()
